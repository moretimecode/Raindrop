using Microsoft.Extensions.Configuration;
using Npgsql;
using NpgsqlTypes;
using Raindrop.AppConfiguration.Database;
using Raindrop.AppConfiguration.Sample.Models;

namespace Raindrop.AppConfiguration.Sample.Scenarios;

public static class DatabaseConfigurationScenario
{
    private const string ConnectionString =
        "Host=localhost;Port=5432;Username=postgres;Password=123456;Database=postgres";

    private const string SchemaName = "raindrop_app_configuration_database_sample";

    public static async Task RunAsync()
    {
        Console.WriteLine("===== SQL 数据库配置示例 =====");

        await PrepareDatabaseAsync();

        var configuration = new ConfigurationBuilder()
            .AddDbConfiguration(new DatabaseConfigOptions
            {
                BuildConnection = () => new NpgsqlConnection(ConnectionString),
                Sql = $"""
                    select app_name, max_items, feature_flags
                    from {SchemaName}.database_configurations
                    order by id
                    """,
                SectionName = "DatabaseConfigs",
                ReloadOnChange = false,
                ReloadFailureBehavior = ConfigurationLoadFailureBehavior.KeepLastKnownGood
            })
            .Build();

        var rows = configuration.GetSection("DatabaseConfigs").Get<List<DatabaseConfigurationRow>>() ?? [];

        foreach (var row in rows)
        {
            Console.WriteLine($"应用名称：{row.AppName}");
            Console.WriteLine($"最大数量：{row.MaxItems}");
            Console.WriteLine($"新界面开关：{row.FeatureFlags.EnableNewUI}");
            Console.WriteLine($"日志开关：{row.FeatureFlags.EnableLogging}");
        }

        Console.WriteLine();
    }

    private static async Task PrepareDatabaseAsync()
    {
        await using var connection = new NpgsqlConnection(ConnectionString);
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"""
            create schema if not exists {SchemaName};

            create table if not exists {SchemaName}.database_configurations
            (
                id integer generated by default as identity primary key,
                app_name text not null,
                max_items integer not null,
                feature_flags jsonb not null
            );

            truncate table {SchemaName}.database_configurations restart identity;

            insert into {SchemaName}.database_configurations
                (app_name, max_items, feature_flags)
            values
                ('Raindrop.Database.Sample', 128, @feature_flags);
            """;

        command.Parameters.AddWithValue(
            "feature_flags",
            NpgsqlDbType.Jsonb,
            """{"EnableNewUI":true,"EnableLogging":true}""");

        await command.ExecuteNonQueryAsync();
    }
}
