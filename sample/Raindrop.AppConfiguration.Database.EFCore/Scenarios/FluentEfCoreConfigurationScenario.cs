using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Raindrop.AppConfiguration;

namespace Raindrop.AppConfiguration.Sample.Scenarios;

/// <summary>
/// 演示 EF Core 配置的 Fluent Builder 重载：包含变更检测、Mapster 映射、KeepLastKnownGood。
/// </summary>
public static class FluentEfCoreConfigurationScenario
{
    private const string ConnectionString =
        "Host=localhost;Port=5432;Username=postgres;Password=123456;Database=postgres";

    private const string SchemaName = "raindrop_sample_fluent_ef";

    public static async Task RunAsync()
    {
        Console.WriteLine("===== EF Core Fluent Builder 配置示例 =====");

        await PrepareDatabaseAsync();

        var configuration = new ConfigurationBuilder()
            .AddEfConfiguration<SampleDbContext, EfConfigEntity, EfAppConfigModel>(options =>
            {
                options
                    .WithDbContextFactory(CreateDbContext)
                    .WithQuery(db => db.Configurations.AsNoTracking().OrderBy(row => row.Id))
                    .WithMapper(rows =>
                    {
                        var row = rows.Single();
                        return new EfAppConfigModel
                        {
                            AppName = row.AppName,
                            MaxItems = row.MaxItems,
                            Features = new FeaturesModel
                            {
                                EnableNewUI = row.EnableNewUI,
                                EnableLogging = true
                            }
                        };
                    })
                    .WithSection("FluentEfConfig")
                    .WithRefreshInterval(TimeSpan.FromSeconds(30))
                    .WithInitialLoadFailureBehavior(ConfigurationLoadFailureBehavior.Throw)
                    .WithReloadFailureBehavior(ConfigurationLoadFailureBehavior.KeepLastKnownGood)
                    .WithChangeDetector((old, @new) =>
                        old.Count != @new.Count ||
                        old.Zip(@new).Any(pair =>
                            pair.First.AppName != pair.Second.AppName ||
                            pair.First.MaxItems != pair.Second.MaxItems));
            })
            .Build();

        var config = configuration.GetSection("FluentEfConfig").Get<EfAppConfigModel>();

        Console.WriteLine($"  应用名称：{config?.AppName}");
        Console.WriteLine($"  最大数量：{config?.MaxItems}");
        Console.WriteLine($"  新界面：{config?.Features.EnableNewUI}");
        Console.WriteLine($"  日志：{config?.Features.EnableLogging}");
        Console.WriteLine();
    }

    private static SampleDbContext CreateDbContext()
    {
        var options = new DbContextOptionsBuilder<SampleDbContext>()
            .UseNpgsql(ConnectionString)
            .Options;

        return new SampleDbContext(options);
    }

    private static async Task PrepareDatabaseAsync()
    {
        await using var connection = new Npgsql.NpgsqlConnection(ConnectionString);
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"""
            create schema if not exists {SchemaName};

            create table if not exists {SchemaName}.ef_configurations
            (
                id integer generated by default as identity primary key,
                app_name text not null,
                max_items integer not null,
                enable_new_ui boolean not null
            );

            truncate table {SchemaName}.ef_configurations restart identity;

            insert into {SchemaName}.ef_configurations
                (app_name, max_items, enable_new_ui)
            values
                ('Raindrop.FluentEf', 512, true);
            """;

        await command.ExecuteNonQueryAsync();
    }

    public sealed class SampleDbContext : DbContext
    {
        public SampleDbContext(DbContextOptions<SampleDbContext> options) : base(options) { }

        public DbSet<EfConfigEntity> Configurations => Set<EfConfigEntity>();

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<EfConfigEntity>(entity =>
            {
                entity.ToTable("ef_configurations", SchemaName);
                entity.HasKey(row => row.Id);
                entity.Property(row => row.Id).HasColumnName("id");
                entity.Property(row => row.AppName).HasColumnName("app_name");
                entity.Property(row => row.MaxItems).HasColumnName("max_items");
                entity.Property(row => row.EnableNewUI).HasColumnName("enable_new_ui");
            });
        }
    }

    public sealed class EfConfigEntity
    {
        public int Id { get; set; }
        public string AppName { get; set; } = string.Empty;
        public int MaxItems { get; set; }
        public bool EnableNewUI { get; set; }
    }

    public sealed class EfAppConfigModel
    {
        public string AppName { get; set; } = string.Empty;
        public int MaxItems { get; set; }
        public FeaturesModel Features { get; set; } = new();
    }

    public sealed class FeaturesModel
    {
        public bool EnableNewUI { get; set; }
        public bool EnableLogging { get; set; }
    }
}
