using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Raindrop.AppConfiguration.Sample.Models;

namespace Raindrop.AppConfiguration.Sample.Scenarios;

public static class EfCoreConfigurationScenario
{
    private const string ConnectionString =
        "Host=localhost;Port=5432;Username=postgres;Password=123456;Database=postgres";

    private const string SchemaName = "raindrop_app_configuration_efcore_sample";

    public static async Task RunAsync()
    {
        Console.WriteLine("===== EF Core 数据库配置示例 =====");

        await PrepareDatabaseAsync();

        var configuration = new ConfigurationBuilder()
            .AddEfConfiguration<SampleConfigurationDbContext, EfConfigurationEntity, EfAppConfig>(
                CreateDbContext,
                db => db.Configurations.AsNoTracking().OrderBy(row => row.Id),
                rows =>
                {
                    var row = rows.Single();

                    return new EfAppConfig
                    {
                        AppName = row.AppName,
                        MaxItems = row.MaxItems,
                        FeatureFlags = new FeatureFlagsConfig
                        {
                            EnableNewUI = row.EnableNewUI,
                            EnableLogging = true
                        }
                    };
                },
                sectionName: "EfConfig",
                refreshInterval: TimeSpan.FromMinutes(5))
            .Build();

        var config = configuration.GetSection("EfConfig").Get<EfAppConfig>();

        Console.WriteLine($"应用名称：{config?.AppName}");
        Console.WriteLine($"最大数量：{config?.MaxItems}");
        Console.WriteLine($"新界面开关：{config?.FeatureFlags.EnableNewUI}");
        Console.WriteLine($"日志开关：{config?.FeatureFlags.EnableLogging}");
        Console.WriteLine();
    }

    private static SampleConfigurationDbContext CreateDbContext()
    {
        var options = new DbContextOptionsBuilder<SampleConfigurationDbContext>()
            .UseNpgsql(ConnectionString)
            .Options;

        return new SampleConfigurationDbContext(options);
    }

    private static async Task PrepareDatabaseAsync()
    {
        await using var connection = new Npgsql.NpgsqlConnection(ConnectionString);
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"""
            create schema if not exists {SchemaName};

            create table if not exists {SchemaName}.ef_configurations
            (
                id integer generated by default as identity primary key,
                app_name text not null,
                max_items integer not null,
                enable_new_ui boolean not null
            );

            truncate table {SchemaName}.ef_configurations restart identity;

            insert into {SchemaName}.ef_configurations
                (app_name, max_items, enable_new_ui)
            values
                ('Raindrop.EfCore.Sample', 256, true);
            """;

        await command.ExecuteNonQueryAsync();
    }

    public sealed class SampleConfigurationDbContext : DbContext
    {
        public SampleConfigurationDbContext(DbContextOptions<SampleConfigurationDbContext> options)
            : base(options)
        {
        }

        public DbSet<EfConfigurationEntity> Configurations => Set<EfConfigurationEntity>();

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<EfConfigurationEntity>(entity =>
            {
                entity.ToTable("ef_configurations", SchemaName);
                entity.HasKey(row => row.Id);
                entity.Property(row => row.Id).HasColumnName("id");
                entity.Property(row => row.AppName).HasColumnName("app_name");
                entity.Property(row => row.MaxItems).HasColumnName("max_items");
                entity.Property(row => row.EnableNewUI).HasColumnName("enable_new_ui");
            });
        }
    }
}
