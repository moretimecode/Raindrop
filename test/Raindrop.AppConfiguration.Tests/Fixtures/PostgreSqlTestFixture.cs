using Npgsql;
using NpgsqlTypes;

namespace Raindrop.AppConfiguration.Tests;

[CollectionDefinition(Name)]
public sealed class PostgreSqlCollection : ICollectionFixture<PostgreSqlTestFixture>
{
    public const string Name = "PostgreSQL";
}

public sealed class PostgreSqlTestFixture : IAsyncLifetime
{
    public const string SchemaName = "raindrop_app_config_tests";

    public string ConnectionString { get; } =
        "Host=localhost;Port=5432;Username=postgres;Password=123456;Database=postgres";

    public async Task InitializeAsync()
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"""
            create schema if not exists {SchemaName};

            create table if not exists {SchemaName}.database_configurations
            (
                id integer generated by default as identity primary key,
                app_name text not null,
                max_items integer not null,
                feature_flags jsonb not null
            );

            create table if not exists {SchemaName}.ef_configurations
            (
                id integer generated by default as identity primary key,
                app_name text not null,
                max_items integer not null,
                enable_new_ui boolean not null
            );

            create table if not exists {SchemaName}.event_consumption_records
            (
                id integer generated by default as identity primary key,
                scenario text not null,
                source text not null,
                message text not null,
                attempt integer not null,
                created_at timestamptz not null default now()
            );
            """;

        await command.ExecuteNonQueryAsync();
    }

    public async Task DisposeAsync()
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"drop schema if exists {SchemaName} cascade;";
        await command.ExecuteNonQueryAsync();
    }

    public NpgsqlConnection CreateConnection()
    {
        return new NpgsqlConnection(ConnectionString);
    }

    public async Task ResetDatabaseConfigurationRowsAsync()
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"""
            truncate table {SchemaName}.database_configurations restart identity;

            insert into {SchemaName}.database_configurations
                (app_name, max_items, feature_flags)
            values
                ('Raindrop.Database', 25, @feature_flags);
            """;
        command.Parameters.AddWithValue("feature_flags", NpgsqlDbType.Jsonb, """{"EnableNewUI":true,"RefreshSeconds":30}""");

        await command.ExecuteNonQueryAsync();
    }

    public async Task ResetEfConfigurationRowsAsync()
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"""
            truncate table {SchemaName}.ef_configurations restart identity;

            insert into {SchemaName}.ef_configurations
                (app_name, max_items, enable_new_ui)
            values
                ('Raindrop.EfCore', 50, true);
            """;

        await command.ExecuteNonQueryAsync();
    }

    public async Task ResetEventConsumptionRecordsAsync()
    {
        await using var connection = CreateConnection();
        await connection.OpenAsync();

        await using var command = connection.CreateCommand();
        command.CommandText = $"truncate table {SchemaName}.event_consumption_records restart identity;";

        await command.ExecuteNonQueryAsync();
    }
}
